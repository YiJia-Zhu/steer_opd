#!/usr/bin/env python3
"""Independent zero-update workflow. Default: CPU preparation only.

--execute is reserved for a later explicit user resumption. The workflow ends
at awaiting_user_review and has no call to campaign.execute/train/acceptance.
"""

import argparse
import fcntl
import os
from pathlib import Path
import random
import csv

from steer_opd.direction_bank import file_sha256
from steer_opd.method_config import resolve_method
from steer_opd.resumable_core import ROOT, atomic_json, digest, read_json
from run_figure8_campaign import Campaign, relative


def prepare(cfg, config_path):
    method = resolve_method(cfg)
    if (method.direction != "T-S" or method.granularity != "global" or method.extractor != "initial"
            or method.gate != "all" or cfg["optimizer_updates"] != 0):
        raise ValueError("First experiment is zero-update T-S/global-initial/all-position")
    run = ROOT / cfg["run_dir"]
    run.mkdir(parents=True, exist_ok=True)
    source = ROOT / cfg["fixed_prefix_source"]
    source_cfg = (read_json(source / "config.json") if (source / "config.json").exists() else
                  read_json(source / "initial_evaluation_reuse.json")["protocol_matches"])
    for key in ["student", "teacher", "shared_vocabulary_size"]:
        if source_cfg[key] != cfg[key]:
            raise ValueError("Fixed teacher/prefix cache model/support protocol changed")
    manifest = read_json(source / "fixed_prefixes/job.json")
    job = manifest["job"]
    if job["model"] != cfg["student"] or job["support_size"] != cfg["shared_vocabulary_size"]:
        raise ValueError("Fixed prefixes were not generated by the frozen Base/protocol")
    if job.get("vector") is not None or job["temperature"] != 1 or job["top_p"] != 1:
        raise ValueError("Expected ordinary Base diagnostic prefixes")
    data_manifest = read_json(ROOT / cfg["data_dir"] / "manifest.json")
    for name in ["opd", "direction", "dev", "aime2025"]:
        rows = read_json(ROOT / cfg["data_dir"] / f"{name}.json")
        if digest(rows) != data_manifest["splits"][name]["hash"]:
            raise ValueError("Frozen data changed")
    if read_json(ROOT / cfg["data_dir"] / "direction.json") != read_json(ROOT / cfg["data_dir"] / "opd.json"):
        raise ValueError("First SV/OPD pool must be identical")
    dev = {row["id"]: row for row in read_json(ROOT / cfg["data_dir"] / "dev.json")}
    prefixes, teacher_hashes = [], {}
    accepted = set(manifest.get("accepted_job_hashes", []) + [manifest["hash"]])
    for request in job["requests"]:
        row = read_json(source / "fixed_prefixes" / f"{request['key']}.json")
        if row["job_hash"] not in accepted or any(row[k] != v for k, v in request.items()):
            raise ValueError("Fixed prefix provenance changed")
        if row["id"] not in dev or row["prompt_token_ids"] != dev[row["id"]]["student_prompt_ids"]:
            raise ValueError("Fixed diagnostic prefixes must use the independent dev split")
        teacher = source / "fixed_teacher_scores" / f"{row['id']}.pt"
        teacher_hashes[row["id"]] = file_sha256(teacher)
        prefixes.append(row)
    if len(prefixes) != 32 or len({r["id"] for r in prefixes}) != 32:
        raise ValueError("Expected exactly 32 distinct frozen dev prefixes")
    random.Random(cfg["seed"]).shuffle(prefixes)
    frozen = {"config_hash": digest(cfg), "prefix_rows_hash": digest(prefixes),
              "teacher_file_hashes": teacher_hashes,
              "select_ids": [r["id"] for r in prefixes[:16]], "confirm_ids": [r["id"] for r in prefixes[16:]],
              "parameter_updates": 0, "selection_uses_test": False}
    path = run / "diagnostic_manifest.json"
    if path.exists() and read_json(path) != frozen:
        raise ValueError("Cannot change a prepared diagnostic split/config")
    atomic_json(path, frozen)
    atomic_json(run / "select_rows.json", prefixes[:16])
    atomic_json(run / "confirm_rows.json", prefixes[16:])
    if not (run / "campaign.json").exists():
        atomic_json(run / "campaign.json", {"status": "paused_by_user", "parameter_updates": 0,
                    "next_action": "explicit_user_resume_for_diagnostics_only", "automatic_opd": False})
    return run


def grid_conditions(cfg):
    result = [{"id": "alpha0", "kind": "bank", "layers": [cfg["layer"]], "rho": 0.0}]
    for layer in cfg["sweep_layers"]:
        for rho in cfg["sweep_rhos"]:
            result.append({"id": f"L{layer}_rho{rho}", "kind": "bank", "layers": [layer],
                           "rho": rho, "control": "positive", "seed": cfg["seed"]})
    if cfg.get("legacy_direction"):
        result.append({"id": "old_independent_L13_rho0.03", "kind": "legacy", "vector_path": cfg["legacy_direction"]})
    return result


def confirmation_conditions(cfg, summaries):
    positives = [value for value in summaries.values() if value["condition"].get("control") == "positive"]
    positives.sort(key=lambda value: (-value["question_weighted_delta_pp"], value["condition"]["id"]))
    selected = [value["condition"] for value in positives[:cfg["confirm_top_n"]]]
    anchor = next(value["condition"] for value in positives
                  if value["condition"]["layers"] == [13] and value["condition"]["rho"] == 0.03)
    selected = list({value["id"]: value for value in [*selected, anchor]}.values())
    result = [{"id": "alpha0", "kind": "bank", "layers": [13], "rho": 0.0}, *selected]
    for condition in selected:
        result.append({**condition, "id": condition["id"] + "_negative", "control": "negative"})
        for seed in cfg["random_direction_seeds"]:
            result.append({**condition, "id": condition["id"] + f"_random{seed}", "control": "random", "seed": seed})
    return result


def write_report(run):
    lines = ["# 训练前固定前缀overlap诊断", "", "参数更新数=0；即时干预结果，完成后等待用户检查。", ""]
    csv_rows = []
    for phase in ["select", "confirm"]:
        summaries = read_json(run / phase / "summaries.json")
        lines += [f"## {phase}", "", "| 候选 | 逐题等权ΔO/百分点 | 95%配对区间 | token加权ΔO | 改善题数 |", "|---|---:|---|---:|---:|"]
        for key, value in summaries.items():
            low, high = value["paired_bootstrap_95ci_pp"]
            lines.append(f"| {key} | {value['question_weighted_delta_pp']:.4f} | [{low:.4f}, {high:.4f}] | {value['token_weighted_delta_pp']:.4f} | {value['improved_questions']}/{value['questions']} |")
            for qid, delta in value["per_question_delta_pp"].items():
                csv_rows.append({"phase": phase, "candidate": key, "question_id": qid, "delta_overlap_pp": delta})
        lines.append("")
    with (run / "per_question.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=["phase", "candidate", "question_id", "delta_overlap_pp"])
        writer.writeheader()
        writer.writerows(csv_rows)
    (run / "README.md").write_text("\n".join(lines) + "\n")


class TuningCampaign(Campaign):
    def __init__(self, cfg, config_path):
        # Dedicated supervisor; do not construct a training campaign or run its
        # acceptance, which includes a real backwards update.
        self.cfg, self.config_path = cfg, str(Path(config_path).resolve())
        self.run = ROOT / cfg["run_dir"]
        self.data, self.runtime = ROOT / cfg["data_dir"], {}
        self.start_ticks = None
        self.lock = (self.run / "campaign.lock").open("a")
        fcntl.flock(self.lock, fcntl.LOCK_EX | fcntl.LOCK_NB)

    def execute_diagnostic(self):
        bank = self.prepare_directions(1)
        root = ROOT / self.cfg["fixed_prefix_source"]
        def phase(name, conditions):
            job = {"config": relative(Path(self.config_path)), "bank": relative(bank),
                   "rows": relative(self.run / f"{name}_rows.json"),
                   "teacher_scores": relative(root / "fixed_teacher_scores"),
                   "output": relative(self.run / name), "conditions": conditions}
            path = self.run / "jobs" / f"score_{name}.json"
            atomic_json(path, job)
            self.stage(f"diagnostic_{name}", ["scripts/pre_opd_overlap_stage.py", "--job", str(path)])
        phase("select", grid_conditions(self.cfg))
        frozen_path = self.run / "confirmation_candidates.json"
        candidates = confirmation_conditions(self.cfg, read_json(self.run / "select/summaries.json"))
        if frozen_path.exists() and read_json(frozen_path) != candidates:
            raise ValueError("Refuse to change frozen confirm candidates")
        atomic_json(frozen_path, candidates)
        phase("confirm", candidates)
        write_report(self.run)
        atomic_json(self.run / "campaign.json", {"status": "awaiting_user_review", "parameter_updates": 0,
                    "automatic_opd": False, "next_action": "show_complete_overlap_table_then_stop"})


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/pre_opd_overlap_tuning.json")
    parser.add_argument("--execute", action="store_true", help="GPU diagnostic only, after explicit user resumption")
    args = parser.parse_args()
    cfg = read_json(args.config)
    run = prepare(cfg, args.config)
    if not args.execute:
        print(f"CPU preparation complete: {run}; parameter updates=0; no GPU launched")
        return
    campaign = TuningCampaign(cfg, args.config)
    try:
        campaign.execute_diagnostic()
    except BaseException as exc:
        campaign.record_failure(exc)
        raise
    finally:
        campaign.lock.close()


if __name__ == "__main__":
    main()
